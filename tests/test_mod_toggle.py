def test_enable_and_disable_update_blacklist_with_standard_header(
    mods_dir: Path, mod_zip_factory, installed_mods_writer
):
    mod_zip_factory(mods_dir, "Root.zip", "Root", deps=[_dep("Dependency")])
    mod_zip_factory(mods_dir, "Dependency.zip", "Dependency")
    installed_mods_writer(mods_dir, [_root("Root")])
    _write_blacklist(mods_dir, ["# old comment", "OldDisabled.zip"])

    mods_to_disable, disable_status = mod_manager.build_disable_plan("Root")
    assert disable_status == mod_manager.ModToggleStatus.READY

    assert mod_manager.disable_mods(mods_to_disable)
    assert (mods_dir / "blacklist.txt").read_text(encoding="utf-8") == (
        _EXPECTED_BLACKLIST_HEADER
        + "Dependency.zip\n"
        + "OldDisabled.zip\n"
        + "Root.zip\n"
    )

    mods_to_enable, enable_status = mod_manager.build_enable_plan("Root")
    assert enable_status == mod_manager.ModToggleStatus.READY

    assert mod_manager.enable_mods(mods_to_enable)
    assert (mods_dir / "blacklist.txt").read_text(encoding="utf-8") == (
        _EXPECTED_BLACKLIST_HEADER + "OldDisabled.zip\n"
    )


def test_uninstall_removes_mods_from_blacklist(
    mods_dir: Path, mod_zip_factory, installed_mods_writer
):
    mod_zip_factory(mods_dir, "Root.zip", "Root", deps=[_dep("Dependency")])
    mod_zip_factory(mods_dir, "Dependency.zip", "Dependency")
    installed_mods_writer(mods_dir, [_root("Root")])
    _write_blacklist(
        mods_dir,
        [
            "Root.zip",
            "Dependency.zip",
            "OtherDisabled.zip",
        ],
    )
    mods_to_uninstall, status = mod_manager.build_uninstall_plan("Root")
    assert status == mod_manager.UninstallModStatus.READY

    assert mod_manager.uninstall_mods(mods_to_uninstall)

    assert (mods_dir / "blacklist.txt").read_text(encoding="utf-8") == (
        _EXPECTED_BLACKLIST_HEADER + "OtherDisabled.zip\n"
    )


def test_uninstall_mods_ignores_root_record_when_root_tracking_disabled(
    mods_dir: Path, mod_zip_factory, monkeypatch
):
    monkeypatch.setattr(config, "_ENABLE_ROOT_INSTALL_TRACK", False)
    mod_zip_factory(mods_dir, "Root.zip", "Root")
    (mods_dir / "installed_mods.yml").write_text("not: [valid\n", encoding="utf-8")
    _write_blacklist(mods_dir, ["Root.zip", "OtherDisabled.zip"])
    mod = next(mod for mod in mod_manager.get_installed_mods() if mod.name == "Root")

    assert mod_manager.uninstall_mods([mod])
    assert (mods_dir / "blacklist.txt").read_text(encoding="utf-8") == (
        _EXPECTED_BLACKLIST_HEADER + "OtherDisabled.zip\n"
    )


def test_root_tracking_commands_report_disabled_when_root_tracking_disabled(
    mods_dir: Path, mod_zip_factory, monkeypatch
):
    monkeypatch.setattr(config, "_ENABLE_ROOT_INSTALL_TRACK", False)
    mod_zip_factory(mods_dir, "Root.zip", "Root")

    disable_mods, disable_status = mod_manager.build_disable_plan("Root")
    enable_mods, enable_status = mod_manager.build_enable_plan("Root")
    uninstall_mods, uninstall_status = mod_manager.build_uninstall_plan("Root")

    assert disable_mods == []
    assert disable_status == mod_manager.ModToggleStatus.ROOT_TRACK_DISABLED
    assert enable_mods == []
    assert enable_status == mod_manager.ModToggleStatus.ROOT_TRACK_DISABLED
    assert uninstall_mods == []
    assert uninstall_status == mod_manager.UninstallModStatus.ROOT_TRACK_DISABLED


def test_build_plans_report_missing_and_unchanged_states(
    mods_dir: Path, mod_zip_factory, installed_mods_writer
):
    mod_zip_factory(mods_dir, "Root.zip", "Root")
    installed_mods_writer(mods_dir, [_root("Root")])

    _, missing_status = mod_manager.build_disable_plan("Missing")
    _, enabled_status = mod_manager.build_enable_plan("Root")

    _write_blacklist(mods_dir, ["Root.zip"])
    _, disabled_status = mod_manager.build_disable_plan("Root")

    assert missing_status == mod_manager.ModToggleStatus.NOT_INSTALLED
    assert enabled_status == mod_manager.ModToggleStatus.ALREADY_ENABLED
    assert disabled_status == mod_manager.ModToggleStatus.ALREADY_DISABLED
