from pathlib import Path

from src import config, mod_manager


def _dep(name: str, version: str = "1.0.0") -> dict[str, str]:
    return {"Name": name, "Version": version}


def _plan_names(mods: list[mod_manager.Mod]) -> list[str]:
    return [mod.name for mod in mods]


def _write_blacklist(mods_dir: Path, entries: list[str]) -> Path:
    blacklist_path = mods_dir / "blacklist.txt"
    blacklist_path.write_text("\n".join(entries) + "\n", encoding="utf-8")
    return blacklist_path


_EXPECTED_BLACKLIST_HEADER = (
    "# This is the blacklist. Lines starting with # are ignored.\n"
    "# Mod folders and archives listed in this file will be disabled.\n"
    "# ExampleFolder\n"
    "# SomeMod.zip\n"
    "\n"
    "# The following blacklist is generated by celeste-mod-manager.\n"
)


def _root(name: str, filename: str | None = None) -> dict[str, str]:
    return {
        "name": name,
        "version": "1.0.0",
        "filename": filename or f"{name}.zip",
    }


def test_disable_plan_includes_enabled_exclusive_dependencies(
    mods_dir: Path, mod_zip_factory, installed_mods_writer
):
    mod_zip_factory(mods_dir, "Root.zip", "Root", deps=[_dep("Alpha"), _dep("Beta")])
    mod_zip_factory(mods_dir, "Alpha.zip", "Alpha")
    mod_zip_factory(mods_dir, "Beta.zip", "Beta")
    installed_mods_writer(mods_dir, [_root("Root")])

    mods, status = mod_manager.build_disable_plan("Root")

    assert status == mod_manager.ModToggleStatus.READY
    assert _plan_names(mods) == ["Root", "Alpha", "Beta"]


